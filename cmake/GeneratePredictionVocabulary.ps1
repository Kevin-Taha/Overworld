param(
    [Parameter(Mandatory = $true)][string]$Source,
    [Parameter(Mandatory = $true)][string]$Output,
    [switch]$Check
)
$ErrorActionPreference = 'Stop'
$expectedHash = '5351FF405B1126EF555791DD4D9798A48E3E9A501A9FC481A9DA957752CFB458'
if ((Get-FileHash -LiteralPath $Source -Algorithm SHA256).Hash -ne $expectedHash) {
    throw 'Vocabulary source does not match the pinned FrequencyWords en_50k.txt'
}
$rows = [IO.File]::ReadAllLines((Resolve-Path -LiteralPath $Source))
if ($rows.Length -ne 50000) { throw 'Expected exactly 50000 source rows' }
$seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$words = [Collections.Generic.List[string]]::new()
$previous = [long]::MaxValue
foreach ($row in $rows) {
    if ($row -cnotmatch '^(\S+) ([0-9]+)$') { throw 'Invalid source row' }
    $word = $Matches[1]
    $frequency = [long]::Parse($Matches[2], [Globalization.CultureInfo]::InvariantCulture)
    if ($frequency -gt $previous) { throw 'Source frequency ranks are not descending' }
    $previous = $frequency
    if ($word -cmatch '^[a-z]{3,24}$' -and $seen.Add($word) -and $words.Count -lt 10000) { $words.Add($word) }
}
if ($words.Count -ne 10000) { throw 'Expected 10000 distinct filtered words' }
$content = "// Generated by cmake\GeneratePredictionVocabulary.ps1; do not edit.`n" +
    "// DATA ONLY: CC-BY-SA-4.0, HermitDave/FrequencyWords, OpenSubtitles2018.`n" +
    "// Attribution, source hash and transformation: third_party\prediction-notices.txt.`n" +
    (($words | ForEach-Object { '"' + $_ + '",' }) -join "`n") + "`n"
$bytes = [Text.Encoding]::ASCII.GetBytes($content)
if ($Check) {
    $existing = [IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $Output))
    if ([Convert]::ToBase64String($existing) -ne [Convert]::ToBase64String($bytes)) {
        throw 'Checked-in vocabulary does not match deterministic transformation'
    }
} else {
    [IO.File]::WriteAllBytes([IO.Path]::GetFullPath($Output), $bytes)
}
Write-Output 'Verified 50000 ranked source rows and 10000 unique ASCII words'
